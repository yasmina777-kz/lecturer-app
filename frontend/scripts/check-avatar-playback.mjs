import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
import * as THREE from 'three';
const path = new URL('../src/sign/avatarPlayback.ts', import.meta.url);
const code = ts.transpileModule(await readFile(path, 'utf8'), {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020}}).outputText.replace('"three"', JSON.stringify(new URL('../node_modules/three/build/three.module.js', import.meta.url).href));
const { AvatarPlayback } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const root = new THREE.Group(), hand = new THREE.Object3D(); hand.name = 'Hand'; root.add(hand);
const sign = new THREE.AnimationClip('sign', 2, [new THREE.VectorKeyframeTrack('Hand.position', [0, 1, 2], [0,0,0, 2,4,6, 0,0,0])]);
const idle = new THREE.AnimationClip('idle', 3, [new THREE.VectorKeyframeTrack('Hand.position', [0, 1.5, 3], [10,0,0, 12,0,0, 10,0,0])]);
const playback = new AvatarPlayback(new THREE.AnimationMixer(root), [sign], idle);
playback.update(0, 'idle', 0);
assert.equal(hand.position.x, 10);
for(let i=0;i<8;i++) playback.update(i*.05, 'playing', .05);
assert.ok(Math.abs(hand.position.x-.7)<1e-6, 'settled transition must contain no idle contribution');
playback.update(1, 'paused', 0);
assert.deepEqual(hand.position.toArray(), [2,4,6]);
for(let i=0;i<120;i++) playback.update(1, 'paused', .016);
assert.deepEqual(hand.position.toArray(), [2,4,6], 'pause must preserve fingers and body');
playback.update(.75, 'paused', 0);
assert.deepEqual(hand.position.toArray(), [1.5,3,4.5], 'scrubbing samples the exact sign');
playback.update(1, 'playing', .03);
assert.deepEqual(hand.position.toArray(), [2,4,6], 'resume must preserve sign source, not restart');
for(let i=0;i<10;i++) playback.update(2, 'idle', .05);
assert.ok(hand.position.x >= 10 && hand.position.x <= 12);
playback.update(1, 'playing', 0);
assert.deepEqual(hand.position.toArray(), [2,4,6], 'jumping to a word must not blend idle into its meaningful pose');
const empty = new AvatarPlayback(new THREE.AnimationMixer(root), [], idle);
empty.update(0, 'idle', .03);
assert.ok(hand.position.x >= 10);
console.log('Avatar playback: idle, crossfade, exact sign poses, pause, seek, resume, word jump and empty input passed.');
