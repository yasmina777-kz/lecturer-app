export function allCourseSigns() {
  const s = new Set<string>();
  for (const p of PHRASES) p.signs.forEach((x) => s.add(x));
  for (const l of GRAMMAR) {
    l.examples.forEach((e) => e.signs.forEach((x) => s.add(x)));
    l.tasks.forEach((t) => t.kind === "order" && t.answer.forEach((x) => s.add(x)));
  }
  return [...s];
}
