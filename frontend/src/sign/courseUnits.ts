/** Step-by-step A1 course: each unit = new signs → recognise them → phrases →
 * sign it yourself (camera) → grammar + dialogue → review. Signs are dictionary
 * labels (native-signer videos); phrases follow RSL word order. */
export type CourseUnit = {
  id: number;
  title: string;
  goal: string;
  words: string[];
  phrases: PhraseItem[];
  grammar?: string;
  dialogue?: string;
  extra?: { to: string; label: string };
  tip: string;
  /** B-level units: a free speaking task recorded in the self-check mirror. */
  speak?: string;
};

export type CefrLevel = "A1" | "A2" | "B1" | "B2";

export function courseUnits(level: CefrLevel | "all" = "A1"): CourseUnit[] {
  const all = [...unitsA1(), ...unitsA2(), ...unitsB1()];
  if (level === "all") return all;
  return all.filter((u) => levelOf(u.id) === level);
}
export const levelOf = (id: number): CefrLevel => (id >= 200 ? "B1" : id >= 100 ? "A2" : "A1");

