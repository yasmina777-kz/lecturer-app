if __name__ == '__main__':
    # Skip candidates whose forms collide with existing entries.
    cat = json.loads((ed.DEST / 'catalog.json').read_text())
    morph = pymorphy3.MorphAnalyzer()
    taken = set()
    for e in cat:
        w = e['label'].lower()
        if ' ' in w or '?' in w:
            taken.add(w); continue
        taken.update(f.word for f in morph.parse(w)[0].lexeme)
    skipped = []
    for k, terms in list(ed.GROUPS.items()):
        keep = []
        for t in terms.split('|'):
            w = t.lower()
            forms = {w} if (' ' in w or '?' in w) else {f.word for f in morph.parse(w)[0].lexeme}
            if forms & taken: skipped.append(t); continue
            taken |= forms; keep.append(t)
        ed.GROUPS[k] = '|'.join(keep)
    print('skipped for collisions:', skipped)
    ed.main()
